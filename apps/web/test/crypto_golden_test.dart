import 'dart:convert';
import 'dart:typed_data';

import 'package:cryptography/cryptography.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:chronowarden/services/crypto_service.dart';

/// Emits a deterministic encryption fixture that the TypeScript client
/// (apps/web-next) must be able to consume byte-for-byte. Run with:
///
///   flutter test test/crypto_golden_test.dart
///
/// then copy the `GOLDEN_VECTORS:` line into
/// apps/web-next/src/lib/__fixtures__/crypto-golden.json.
void main() {
  test('emit golden crypto vectors', () async {
    final passphrase = 'golden-test-passphrase';

    final salt = Uint8List.fromList(List<int>.generate(16, (i) => (i * 3 + 1) & 0xff));
    final dekBytes = Uint8List.fromList(List<int>.generate(32, (i) => (i * 7 + 3) & 0xff));
    final dek = SecretKey(dekBytes);

    final masterKey = await CryptoService.deriveMasterKey(passphrase, salt);
    final wrappedDek = await CryptoService.wrapDekBase64(dek, masterKey);

    final plaintext = '{"note":"hello","minutes":42,"nested":{"a":1}}';
    final ciphertext = await CryptoService.encrypt(plaintext, dek);

    final recoveryPhrase = await CryptoService.dekToMnemonic(dek);
    final recoveryHash = CryptoService.hashRecoveryPhrase(recoveryPhrase);

    final vectors = {
      'note': 'Generated by apps/web/test/crypto_golden_test.dart (Dart).',
      'passphrase': passphrase,
      'kek_iterations': CryptoService.kekIterations,
      'salt_b64': base64.encode(salt),
      'dek_b64': base64.encode(dekBytes),
      'wrapped_dek_b64': wrappedDek,
      'plaintext': plaintext,
      'ciphertext_b64': ciphertext,
      'recovery_phrase': recoveryPhrase,
      'recovery_hash_b64': recoveryHash,
    };

    // ignore: avoid_print
    print('GOLDEN_VECTORS:${jsonEncode(vectors)}');
  });
}
