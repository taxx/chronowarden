#!/usr/bin/env bash
#
# Generate build metadata from the git history:
#
#   public/version.json  — served at /version.json; the running app compares it
#                          with the commit baked into its bundle
#   public/CHANGELOG.md  — rendered by the "What's New" screen
#
# Run before committing (part of the release routine). Generated, not hand-written.
set -euo pipefail

cd "$(dirname "$0")/.."

if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  COMMIT="$(git rev-parse --short HEAD)"
  HAS_GIT=1
else
  COMMIT="dev"
  HAS_GIT=0
fi

VERSION="$(node -p "require('./package.json').version" 2>/dev/null || echo "0.0.0")"
BUILT_AT="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

mkdir -p public

cat >public/version.json <<EOF
{
  "version": "$VERSION",
  "commit": "$COMMIT",
  "built_at": "$BUILT_AT"
}
EOF
chmod 644 public/version.json

MAX_COMMITS="${1:-300}"
TMP="$(mktemp)"
{
  echo "# Changelog"
  echo
  echo "<!-- Generated by tool/generate_metadata.sh from the git history."
  echo "     Do not edit by hand — update the script or its output instead. -->"
  echo
  if [ "$HAS_GIT" -eq 1 ]; then
    current_date=""
    git log \
      --no-merges \
      --date=short \
      --pretty=format:'%ad%x09%s%x09%h' \
      -n "$MAX_COMMITS" |
      while IFS=$'\t' read -r date subject hash; do
        [ -z "$date" ] && continue
        if [ "$date" != "$current_date" ]; then
          [ -n "$current_date" ] && echo
          echo "## $date"
          echo
          current_date="$date"
        fi
        echo "- $subject (\`$hash\`)"
      done
  else
    echo "## unknown"
    echo
    echo "- Changelog unavailable (no git history)"
  fi
} >"$TMP"
mv "$TMP" public/CHANGELOG.md
chmod 644 public/CHANGELOG.md

echo "Wrote public/version.json + public/CHANGELOG.md (version $VERSION, commit $COMMIT)."
